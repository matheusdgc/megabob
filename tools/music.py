"""Prepare the soundtrack: art/raw/soundtrack -> public/assets/music.

    py -3 tools/music.py

The selection and the use of each track are in docs/soundtrack.md; the loop points live in
src/data/music.ts. Loudness is evened out in the game itself (src/systems/audioMath.ts
measures each track when it loads), so a plain copy already plays at matching volumes.

With ffmpeg on PATH, each track is re-encoded to OGG Vorbis ~128 kbps (sample-exact loops) plus
an MP3 fallback for browsers without Vorbis; without it the sources are copied as they are. MP3s
carry encoder padding that can leave a tiny gap at a loop seam, so prefer the ffmpeg build.
Writes src/data/musicFiles.ts (the files of each track, best format first).
"""
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'art' / 'raw' / 'soundtrack'
OUT = ROOT / 'public' / 'assets' / 'music'

# game id -> source file (see docs/soundtrack.md)
TRACKS = {
    'title': '01_titulo__8Bit_Title_Screen.mp3',
    'select': '02_selecao_de_fases__Select_Mountain_120BPM.ogg',
    'memory_leak': '03_fase_memory_leak__Sewer_Nightclub.ogg',
    'race_condition': '04_fase_race_condition__Castle_Stage_180BPM.ogg',
    'null_pointer': '05_fase_null_pointer__CYBER_CELESTE.mp3',
    'boss': '06_chefes__8bit_Action_Boss_Battle_145BPM.ogg',
    'fortress': '07_fortaleza__Last_Mission_FULL.mp3',
    'tech_debt_1': '08a_tech_debt_fase1__phantasticbeats-boss-fight-301722.mp3',
    'tech_debt_2': '08b_tech_debt_fase2__Final_Stand_Phase4_FinalMax.ogg',
    'credits': '09_creditos__lightyeartraxx-kim-lightyear-legends-109307.mp3',
}


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    ffmpeg = shutil.which('ffmpeg')
    total = 0
    files: dict[str, list[str]] = {}
    for key, name in TRACKS.items():
        src = SRC / name
        if not src.exists():
            print(f'missing {src}', file=sys.stderr)
            return 1
        for old in OUT.glob(key + '.*'):
            old.unlink()
        if ffmpeg:
            outs = [OUT / f'{key}.ogg', OUT / f'{key}.mp3']
            codecs = [['-c:a', 'libvorbis', '-q:a', '4'], ['-c:a', 'libmp3lame', '-b:a', '128k']]
            for dst, codec in zip(outs, codecs):
                subprocess.run([ffmpeg, '-y', '-loglevel', 'error', '-i', str(src), '-vn', '-ar', '44100', *codec, str(dst)],
                               check=True)
        else:
            outs = [OUT / (key + src.suffix.lower())]
            shutil.copyfile(src, outs[0])
        files[key] = [f'assets/music/{o.name}' for o in outs]
        for o in outs:
            total += o.stat().st_size
            print(f'{o.name:24} {o.stat().st_size / 1e6:5.2f} MB')
    print(f'total {total / 1e6:.1f} MB' + ('' if ffmpeg else ' (copied: install ffmpeg to re-encode)'))
    lines = ['// Generated by tools/music.py: the files of each track, best format first.',
             'export const MUSIC_FILES: Record<string, readonly string[]> = {']
    lines += [f"  {k}: [{', '.join(repr(f) for f in v)}]," for k, v in files.items()]
    lines += ['};', '']
    out = ROOT / 'src' / 'data' / 'musicFiles.ts'
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    return 0


if __name__ == '__main__':
    sys.exit(main())
